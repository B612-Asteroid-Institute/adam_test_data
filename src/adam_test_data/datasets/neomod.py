import numpy as np
import numpy.typing as npt
import pandas as pd
import pyarrow as pa
from adam_core.coordinates import KeplerianCoordinates
from adam_core.coordinates.origin import Origin
from adam_core.orbits import Orbits
from adam_core.time import Timestamp

from ..populations import PhotometricProperties, SmallBodies


def color_distribution_neos(
    pv: npt.NDArray[np.float64], Hv: npt.NDArray[np.float64], seed: int = 42
) -> PhotometricProperties:
    """
    Create a color distribution for NEOs drawn from the NEOMOD model.

    Parameters
    ----------
    pv : np.ndarray
        Geometric visual albedo of the NEOs.
    Hv : np.ndarray
        Absolute visual magnitude of the NEOs.
    seed : int, optional
        Seed for the random number generator.

    Returns
    -------
    photometric_properties : PhotometricProperties
        The photometric properties of the NEOs (with r-band assumed to be the main filter)
    """
    C = np.where(pv < 0.1)[0]
    S = np.where(pv >= 0.1)[0]

    C_num = len(C)
    S_num = len(S)

    u_r = np.empty(len(pv), dtype=np.float64)
    g_r = np.empty(len(pv), dtype=np.float64)
    r_i = np.empty(len(pv), dtype=np.float64)
    r_z = np.empty(len(pv), dtype=np.float64)
    r_y = np.empty(len(pv), dtype=np.float64)
    V_r = np.empty(len(pv), dtype=np.float64)

    rng = np.random.default_rng(seed=seed)

    u_r[S] = rng.normal(1.62, 0.13, S_num)
    g_r[S] = rng.normal(0.78, 0.03, S_num)
    r_i[S] = rng.normal(0.5, 0.01, S_num)
    r_z[S] = rng.normal(0.71, 0.03, S_num)
    r_y[S] = rng.normal(0.92, 0.07, S_num)
    V_r[S] = rng.normal(0.35, 0.01, S_num)

    u_r[C] = rng.normal(1.28, 0.11, C_num)
    g_r[C] = rng.normal(0.62, 0.02, C_num)
    r_i[C] = rng.normal(0.43, 0.01, C_num)
    r_z[C] = rng.normal(0.72, 0.02, C_num)
    r_y[C] = rng.normal(0.93, 0.07, C_num)
    V_r[C] = rng.normal(0.27, 0.01, C_num)

    photometric_properties = PhotometricProperties.from_kwargs(
        H_mf=Hv - V_r,
        u_mf=u_r,
        g_mf=g_r,
        r_mf=pa.repeat(0, len(pv)),
        i_mf=-r_i,
        z_mf=-r_z,
        y_mf=-r_y,
    )

    return photometric_properties


def load_NEOMOD(file: str, seed: int = 42) -> SmallBodies:
    """
    Load the NEOMOD population model from a file generated by NEOMOD2 or NEOMOD3.

    This function will assign angles Right Ascension of the Ascending Node, Argument of Perihelion, and Mean Anomaly from
    a uniform distribution. Additionaly, the colors are assigned using color_distribution_neos.

    The model can be downloaded from:
        https://www2.boulder.swri.edu/~davidn/NEOMOD_Simulator/

    Parameters
    ----------
    file : str
        Output file generated by NEOMOD2 or NEOMOD3.

    Returns
    -------
    neomod : SmallBodies
        The NEOMOD population model.
    """
    neomod_df = pd.read_csv(
        file, sep="\\s+", header=None, names=["H_V", "a", "e", "i", "D_km", "p_V"]
    )

    rng = np.random.default_rng(seed)

    # From the comments in the file
    J2000 = 2451545.0
    time = Timestamp.from_jd([J2000 for _ in range(len(neomod_df))], scale="tdb")

    orbit_ids = pa.array([f"NEOMOD_{i:07d}" for i in range(len(neomod_df))])
    orbits = Orbits.from_kwargs(
        orbit_id=orbit_ids,
        object_id=np.array(neomod_df.index.values.astype(str), dtype="object"),
        coordinates=KeplerianCoordinates.from_kwargs(
            a=neomod_df["a"],
            e=neomod_df["e"],
            i=neomod_df["i"],
            raan=rng.uniform(0, 360, len(neomod_df)),
            ap=rng.uniform(0, 360, len(neomod_df)),
            M=rng.uniform(0, 360, len(neomod_df)),
            time=time,
            origin=Origin.from_kwargs(code=pa.repeat("SUN", len(neomod_df))),
            frame="ecliptic",
        ).to_cartesian(),
    )

    photometric_properties = color_distribution_neos(
        neomod_df["p_V"], neomod_df["H_V"], seed=seed
    )

    return SmallBodies.from_kwargs(
        orbits=orbits,
        properties=photometric_properties,
        name="NEOMOD",
    )
